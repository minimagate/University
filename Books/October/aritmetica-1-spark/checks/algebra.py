#!/usr/bin/env python3
"""Independent exact checks for Spark chapters 9–12 and their answers."""
from fractions import Fraction
from math import gcd, lcm
from itertools import permutations
import json

checks = []
def check(name, condition):
    assert condition, name
    checks.append(name)

def units(n):
    return [a for a in range(n) if gcd(a,n)==1]

def order(a,n):
    assert gcd(a,n)==1
    v=1
    for r in range(1,n+1):
        v=v*a%n
        if v==1:
            return r
    raise AssertionError('no return')

def roots(n,b):
    return [x for x in range(n) if (x*x-b)%n==0]

def compose(p,q):
    return tuple(p[q[x]-1] for x in range(len(p)))

def perm_power(p,k):
    v=tuple(range(1,len(p)+1))
    for _ in range(k):
        v=compose(p,v)
    return v

# Groups, rings, fields and the algebraic Chinese remainder map.
check('Z multiplication: 2 has no integer inverse', not any(2*x==1 for x in range(-100,101)))
check('units mod12', units(12)==[1,5,7,11])
check('opposite of3 mod12', (3+9)%12==0 and gcd(3,12)>1)
check('units mod5', units(5)==[1,2,3,4])
check('inverses mod5', all((a*b)%5==1 for a,b in [(1,1),(2,3),(3,2),(4,4)]))
check('zero is not unit mod5', 0 not in units(5))
for n in range(2,31):
    prime=all(n%d for d in range(2,n))
    check(f'field criterion mod{n}', (len(units(n))==n-1)==prime)
check('CRT6 to2times3 is bijection', len({(x%2,x%3) for x in range(6)})==6)
check('CRT noncoprime0mod2 1mod4 impossible', not any(x%2==0 and x%4==1 for x in range(8)))
check('map6to3 well-defined', all(a%3==b%3 for a in range(-12,13) for b in range(-12,13) if a%6==b%6))
check('map6to3 preserves operations', all(((a+b)%6)%3==(a%3+b%3)%3 and ((a*b)%6)%3==(a%3*b%3)%3 for a in range(6) for b in range(6)))
check('map6to3 noninjective witness', 0%3==3%3 and 0%6!=3%6)

# Subgroups, integer multiples, and permutations; concrete examples independently enumerated.
check('2Z union3Z not closed', (2%2==0) and (3%3==0) and (5%2!=0) and (5%3!=0))
check('generated3 mod12', sorted({3*k%12 for k in range(12)})==[0,3,6,9])
check('generated4 mod12', sorted({4*k%12 for k in range(12)})==[0,4,8])
check('clock subgroup intersection', set(3*k%12 for k in range(12))&set(4*k%12 for k in range(12))=={0})
check('generated8 mod12', sorted({8*k%12 for k in range(12)})==[0,4,8])
check('additive order8 mod12', next(k for k in range(1,13) if 8*k%12==0)==3)
check('generated8 subtraction closure', all((x-y)%12 in [0,4,8] for x in [0,4,8] for y in [0,4,8]))
sigma=(2,3,1);tau=(2,1,3)
check('sigma tau is13', compose(sigma,tau)==(3,2,1))
check('tau sigma is23', compose(tau,sigma)==(1,3,2))
check('S3 size6', len(list(permutations([1,2,3])))==6)
rho=(2,3,1,5,4)
check('rho square', perm_power(rho,2)==(3,1,2,4,5))
check('rho inverse', compose(rho,(3,1,2,5,4))==(1,2,3,4,5))
check('rho order6', next(k for k in range(1,7) if perm_power(rho,k)==(1,2,3,4,5))==lcm(3,2)==6)
check('4th roots unit', all(z**4==1 for z in [1,1j,-1,-1j]))

# Exponent equations and decimal expansions.
check('4 powers mod17', [pow(4,k,17) for k in range(5)]==[1,4,16,13,1])
check('order4 mod17', order(4,17)==4)
check('invertible2 not generated by4 mod17', gcd(2,17)==1 and 2 not in [pow(4,k,17) for k in range(4)])
check('4^x=16 exponent class', all((pow(4,k,17)==16)==(k%4==2) for k in range(100)))
check('3 powers mod7', [pow(3,k,7) for k in range(7)]==[1,3,2,6,4,5,1])
check('3 powers mod13', [pow(3,k,13) for k in range(4)]==[1,3,9,1])
check('61 residues', 61%7==5 and 61%13==9)
check('3^5 direct', 3**5==243==2*91+61)
check('3 order mod91', order(3,91)==6)
check('3^x=61 mod91', all((pow(3,k,91)==61)==(k%6==5) for k in range(120)))
check('2 powers mod7 exercise', [pow(2,k,7) for k in range(4)]==[1,2,4,1])
check('2^x=4 mod7 exercise', all((pow(2,k,7)==4)==(k%3==2) for k in range(100)))
r=1;rs=[r];digits=[]
for _ in range(6):
    d,r=divmod(10*r,7);digits.append(d);rs.append(r)
check('1/7 remainder cycle', rs==[1,3,2,6,4,5,1])
check('1/7 digit cycle', ''.join(map(str,digits))=='142857')
check('first1/7 division', 10==1*7+3)
check('second1/7 division', 30==4*7+2)
check('0.bar34 fraction', Fraction(34,99)==Fraction(3434-34,9900))
check('0.1bar6 fraction', Fraction(16-1,90)==Fraction(1,6))
check('3/40 finite', Fraction(3,40)==Fraction(75,1000))
check('ord3(10)=1', order(10,3)==1)
check('7/80 four digits', Fraction(7,80)==Fraction(875,10000) and all((7*10**k)%80!=0 for k in range(4)))
check('0.2bar7 fraction', Fraction(27-2,90)==Fraction(5,18))

# Quadratics and all lifting branches, checked by exhaustive residue search.
check('squares mod5', [x*x%5 for x in range(5)]==[0,1,4,4,1])
check('roots1 mod5', roots(5,1)==[1,4])
check('zero divisors mod4', 2*2%4==0)
check('roots1 mod15', roots(15,1)==[1,4,11,14])
check('discriminant example', 25-12==13 and 13%11==2)
check('squares0to5 mod11', [x*x%11 for x in range(6)]==[0,1,4,9,5,3])
check('quadratic11 impossible', not any((x*x+5*x+3)%11==0 for x in range(11)))
check('sqrt6 mod25 branch1', [h for h in range(5) if ((1+5*h)**2-6)%25==0]==[3])
check('sqrt6 mod25 branch4', [h for h in range(5) if ((4+5*h)**2-6)%25==0]==[1])
check('sqrt6 mod25 roots', roots(25,6)==[9,16])
check('sqrt6 mod25 explicit squares', 81==3*25+6 and 256==10*25+6)
check('singular three branches', roots(9,0)==[0,3,6])
check('singular no branch', roots(9,3)==[])
check('sqrt6 mod75', roots(75,6)==[9,66])
check('CRT sqrt6 first branch', [k for k in range(3) if (9+25*k)%3==0]==[0])
check('CRT sqrt6 second branch', [k for k in range(3) if (16+25*k)%3==0]==[2])
check('sqrt4 mod25 first branch', [h for h in range(5) if ((2+5*h)**2-4)%25==0]==[0])
check('sqrt4 mod25 second branch', [h for h in range(5) if ((3+5*h)**2-4)%25==0]==[4])
check('sqrt4 mod25 roots', roots(25,4)==[2,23] and 23**2==529==21*25+4)
check('roots1 mod3', roots(3,1)==[1,2])
check('roots1 mod4', roots(4,1)==[1,3])
check('roots1 mod12', roots(12,1)==[1,5,7,11])
for n,r in [(2,1),(4,1),(6,2),(12,2),(30,3),(72,2),(210,4)]:
    check(f'idempotents2^r mod{n}', sum(x*(x-1)%n==0 for x in range(n))==2**r)

print(json.dumps({'status':'passed','checks':len(checks),'labels':checks}, ensure_ascii=False, indent=2))
